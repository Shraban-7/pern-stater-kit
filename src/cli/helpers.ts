export function getCliVersion(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  const candidates = [join(here, '../../package.json'), join(here, '../../../package.json')];
  for (const candidate of candidates) {
    try {
      const pkg = JSON.parse(readFileSync(candidate, 'utf8')) as { name?: string; version?: string };
      if (pkg.name === 'pern-starter' && pkg.version) return pkg.version;
    } catch {
      // keep looking
    }
  }
  return '1.0.0';
}

export async function loadProject(cwd = process.cwd()): Promise<{ config: StarterConfig; cwd: string }> {
  try {
    const config = await readManifest(cwd);
    if (!config) {
      throw new CliError(
        'No starter.json found',
        'This command must be run inside a project generated by pern-starter.',
        'Run this command from the project root, or create a project with `pern-starter new <name>`.',
      );
    }
    return { config, cwd };
  } catch (error) {
    if (error instanceof CliError) throw error;
    const message = error instanceof Error ? error.message : String(error);
    throw new CliError(
      'Could not read starter.json',
      message,
      'Fix starter.json so it matches the pern-starter schema, then retry.',
    );
  }
}

export async function writeManifest(cwd: string, config: StarterConfig): Promise<void> {
  const manifest: Manifest = {
    version: 1,
    stack: 'PERN',
    generatedAt: new Date().toISOString(),
    generatorVersion: getCliVersion(),
    config,
  };
  await writeFileEnsured(join(cwd, 'starter.json'), `${JSON.stringify(manifest, null, 2)}\n`);
}

export async function writePlannedFiles(
  files: PlannedFile[],
  cwd: string,
  options: { force?: boolean; dryRun?: boolean } = {},
): Promise<{ created: string[]; modified: string[]; skipped: string[] }> {
  const created: string[] = [];
  const modified: string[] = [];
  const skipped: string[] = [];

  for (const file of files) {
    const abs = join(cwd, file.path);
    const exists = pathExists(abs);
    if (options.dryRun) {
      if (exists) modified.push(file.path);
      else created.push(file.path);
      continue;
    }
    if (exists && !options.force) {
      skipped.push(file.path);
      continue;
    }
    const formatted = await formatGeneratedFile(file.path, file.contents);
    await writeFileEnsured(abs, formatted);
    if (exists) modified.push(file.path);
    else created.push(file.path);
  }

  return { created, modified, skipped };
}

