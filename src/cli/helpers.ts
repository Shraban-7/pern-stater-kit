export function resolveFeatureId(input: string): string {
  const needle = input.trim().toLowerCase();
  if (!needle) {
    throw new CliError('Feature id is required', undefined, 'Pass a feature id from `pern-starter features`.');
  }
  if (FEATURE_ALIASES[needle]) return FEATURE_ALIASES[needle];

  const exact = FEATURE_CATALOG.find((feature) => feature.id.toLowerCase() === needle);
  if (exact) return exact.id;

  const byName = FEATURE_CATALOG.filter((feature) => feature.name.toLowerCase() === needle);
  if (byName.length === 1) return byName[0]!.id;

  const bySuffix = FEATURE_CATALOG.filter(
    (feature) => feature.id.toLowerCase() === needle || feature.id.toLowerCase().endsWith(`-${needle}`),
  );
  if (bySuffix.length === 1) return bySuffix[0]!.id;
  if (bySuffix.length > 1) {
    throw new CliError(
      `Ambiguous feature "${input}"`,
      `Matches: ${bySuffix.map((feature) => feature.id).join(', ')}`,
      'Use a full feature id from `pern-starter features`.',
    );
  }

  throw new CliError(
    `Unknown feature: ${input}`,
    `"${input}" is not in the feature catalog.`,
    'Run `pern-starter features` to see available ids.',
  );
}

export function autoFixConfig(config: StarterConfig): StarterConfig {
  const next = structuredClone(config);
  if (next.queue === 'bullmq' && next.cache !== 'redis') next.cache = 'redis';
  if (next.backend.api.includes('graphql') && !next.backend.graphqlServer) {
    next.backend.graphqlServer = 'apollo';
  }
  if (next.events === 'redis-pubsub' && next.cache !== 'redis') next.cache = 'redis';
  if (next.events === 'queue' && next.queue !== 'bullmq') next.queue = 'bullmq';
  if (next.events === 'queue' && next.cache !== 'redis') next.cache = 'redis';
  return next;
}

function dependencyIdFromIssue(issue: ValidationIssue): string | undefined {
  const fromMessage = issue.message.match(/Dependency:\s*([A-Za-z0-9._+-]+)/);
  if (fromMessage?.[1]) return fromMessage[1];
  if (issue.path === 'queue' || issue.message.toLowerCase().includes('bullmq requires redis')) {
    return 'cache-redis';
  }
  if (issue.path === 'backend.graphqlServer') return 'graphql-apollo';
  if (issue.fix?.startsWith('Add ')) {
    const match = issue.fix.match(/Add\s+([A-Za-z0-9._+-]+)/);
    if (match?.[1] && match[1] !== 'Redis') return match[1];
  }
  return undefined;
}

export async function resolveMissingDependencies(
  config: StarterConfig,
  options: { yes?: boolean },
): Promise<StarterConfig> {
  const engine = new GenerationEngine();
  let next = structuredClone(config);
  const asked = new Set<string>();

  for (let i = 0; i < 8; i += 1) {
    const missing = [
      ...engine.dependency.requiredPrompts(next),
      ...engine.conflicts.detect(next).filter((issue) => issue.code === 'MISSING_DEPENDENCY'),
    ];
    if (!missing.length) return next;

    for (const issue of missing) {
      const depId = dependencyIdFromIssue(issue);
      const key = depId ?? issue.path ?? issue.message;
      if (asked.has(key)) {
        throw new CliError(issue.message, issue.message, issue.fix);
      }
      asked.add(key);

      const feature = depId ? engine.features.get(depId) : undefined;
      const name = feature?.name ?? depId ?? 'the required dependency';
      let add = Boolean(options.yes);
      if (!options.yes) {
        const answer = await confirm({
          message: `Add ${name} automatically?`,
          initialValue: true,
        });
        add = handleCancel(answer);
      }

      if (!add) {
        throw new CliError(
          issue.message,
          `${name} is required by the current selection and was not added.`,
          issue.fix ?? `Re-run and accept adding ${name}, or disable the dependent feature.`,
        );
      }

      if (depId) next = applyFeatureToConfig(next, depId);
      if (depId === 'cache-redis' || issue.path === 'queue') next.cache = 'redis';
      if (depId === 'graphql-apollo' || issue.path === 'backend.graphqlServer') {
        next.backend.graphqlServer = next.backend.graphqlServer ?? 'apollo';
      }
      if (depId === 'queue-bullmq') next.queue = 'bullmq';
    }
  }

  return next;
}

export async function confirmContinue(message = 'Continue?', yes?: boolean): Promise<boolean> {
  if (yes) return true;
  if (!process.stdin.isTTY) return true;
  const answer = await confirm({ message, initialValue: true });
  return handleCancel(answer);
}

export function planDelta(before: GenerationPlan, after: GenerationPlan): {
  create: PlannedFile[];
  modify: PlannedFile[];
  remove: PlannedFile[];
  packages: GenerationPlan['packages'];
  env: GenerationPlan['env'];
} {
  const beforeMap = new Map(before.files.map((file) => [file.path, file]));
  const afterMap = new Map(after.files.map((file) => [file.path, file]));
  const create: PlannedFile[] = [];
  const modify: PlannedFile[] = [];
  const remove: PlannedFile[] = [];

  for (const file of after.files) {
    const previous = beforeMap.get(file.path);
    if (!previous) create.push({ ...file, action: 'create' });
    else if (previous.contents !== file.contents) modify.push({ ...file, action: 'modify' });
  }
  for (const file of before.files) {
    if (!afterMap.has(file.path)) remove.push(file);
  }

  const beforePkgs = new Set(before.packages.map((pkg) => `${pkg.workspace}:${pkg.name}`));
  const packages = after.packages.filter((pkg) => !beforePkgs.has(`${pkg.workspace}:${pkg.name}`));
  const beforeEnv = new Set(before.env.map((item) => item.key));
  const env = after.env.filter((item) => !beforeEnv.has(item.key));

  return { create, modify, remove, packages, env };
}

export function printInstallPlan(delta: ReturnType<typeof planDelta>, cwd: string): void {
  const files: PlannedFile[] = [
    ...delta.create,
    ...delta.modify.map((file) => ({ ...file, action: 'modify' as const })),
  ];
  printDryRun(
    {
      projectName: '',
      destination: cwd,
      files,
      packages: delta.packages,
      env: delta.env,
      dockerServices: [],
      scripts: {},
      features: [],
      warnings: [],
      notes: [],
    },
    cwd,
  );
  if (delta.remove.length) {
    console.log('Files that would be removed:');
    for (const file of delta.remove) {
      console.log(`- ${file.path}`);
    }
    console.log();
  }
}

export async function runInstall(
  pm: PackageManager,
  cwd: string,
): Promise<void> {
  const bin = pm === 'npm' ? 'npm' : pm;
  const args = pm === 'yarn' ? ['install'] : ['install'];
  try {
    await execFileAsync(bin, args, {
      cwd,
      timeout: 10 * 60 * 1000,
      windowsHide: true,
      shell: process.platform === 'win32',
    });
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new CliError(
      `${pm} install failed`,
      message,
      `Run \`${pm} install\` in ${cwd} after fixing the error.`,
    );
  }
}

export function selectedFeatureNames(config: StarterConfig): string[] {
  const ids = featuresFromConfig(config);
  return ids.map((id) => FEATURE_CATALOG.find((feature) => feature.id === id)?.name ?? id);
}

export function dumpConfig(config: StarterConfig, format: 'json' | 'yaml' = 'yaml'): string {
  if (format === 'json') return `${JSON.stringify(config, null, 2)}\n`;
  return stringifyYaml(config);
}

export async function safeExec(
  command: string,
  args: string[],
  options: { timeout?: number } = {},
): Promise<{ ok: boolean; output: string }> {
  try {
    const { stdout, stderr } = await execFileAsync(command, args, {
      timeout: options.timeout ?? 8000,
      windowsHide: true,
      shell: process.platform === 'win32',
    });
    return { ok: true, output: `${stdout}${stderr}`.trim() };
  } catch {
    return { ok: false, output: '' };
  }
}

export function isInteractive(yes?: boolean): boolean {
  return Boolean(process.stdin.isTTY) && !yes;
}
